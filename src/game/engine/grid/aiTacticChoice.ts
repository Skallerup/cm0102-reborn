/** Tactics::record_tactic_result 0x896290 (kaldt efter kampen ved 0x6ba9a0, når fixture-id ≠ −2) for ét hold: springes helt over (begge
 *  hold), hvis ét af holdene er menneskestyret (0x600a50). `gf`/`ga` = slutresultatet inkl. forlænget spilletid (fixture +0x47/+0x48, ellers
 *  +0x43/+0x44; 0x7e4750). Med F = max(mål for, 1), A = max(mål imod, 1), P = max(point, 1), G = max(kampe, 1), p = P/G, f = F/G, a = G/A:
 *  perf = [f²p²a, f·p³·a, f·p²·a²]. */
export function recordTacticResult(stats: TacticStat[], index: number, gf: number, ga: number): void {
  const e = stats[index];
  e.games++;
  if (gf > ga) { e.won++; e.pts += 3; } else if (gf === ga) { e.drawn++; e.pts += 1; } else e.lost++;
  e.gf += gf; e.ga += ga;
  const F = Math.max(e.gf, 1), A = Math.max(e.ga, 1), P = Math.max(e.pts, 1), G = Math.max(e.games, 1);
  const p = P / G, f = F / G, a = G / A;
  e.perf = [f * f * p * p * a, a * f * p * p * p, a * a * f * p * p];
}

export interface AiTacticInput {
  /** Kandidaterne (pick_teams liste: truppens spillere med spillerdata, ikke skadede (2), ikke udelukkede/på landsholdet/udlejede). */
  players: ChoicePlayer[];
  /** AI-tilstanden fra 0x6df460 for holdet (1 jagter … 4 forsvar, 5 slap af). */
  mode: number;
  /** null = ingen manager (team+0x1f = 0): intet manager-led og ingen yndlingsfaktor. */
  manager: ChoiceManager | null;
  stats?: TacticStat[];
  /** max(8·klubbens omdømme +0x80, 2000) – fælles for alle taktikker, påvirker kun skalaen. */
  divisor?: number;
  /** Motorens byte +0 ≠ 0 (0x6e0289): vælg rand(listens længde) uden at score. */
  randomPick?: boolean;
  /** rand(n) → 0..n−1 (originalens 0x90cfc0); kun brugt med randomPick. */
  rand?: (n: number) => number;
  list?: AiTacticEntry[];
  /** pick_teams flag til 0x6e2f20 (kun 0x400/0x200 påvirker P). */
  flags?: number;
}

/** den sekundære maskes bit, tællerens plads og positionen (før en ny liste pr. plads og taktik) */
const SEC_MASK: readonly (readonly [number, number, number])[] = [[2, 0, 1], [4, 0, 2], [8, 1, 3], [0x10, 2, 4], [0x20, 3, 5], [0x40, 4, 6]];
/** 0x6e0230 med arg4 = 2. Returnerer indeks i listen (AI_TACTIC_LIST; `AI_TACTIC_LIST[i].preset` = indeks i PRESET_TACTICS eller −1)
 *  og scoren pr. taktik. Første strengt største vinder (0x6e0b83). */
export function chooseAiTactic(inp: AiTacticInput): { index: number; scores: number[] } {
  const list = inp.list ?? AI_TACTIC_LIST;
  if (inp.randomPick) return { index: (inp.rand ?? ((n) => Math.floor(Math.random() * n)))(list.length), scores: [] };
  const T = cellTable(inp.players, inp.flags);
  const n = inp.players.length, mode = inp.mode, mgr = inp.manager, div = inp.divisor ?? 2000;
  const col = mode === 1 ? 0 : mode >= 3 && mode <= 5 ? 2 : 1;           // +0x10 / +0x18 / +0x20
  const scores: number[] = [];
  let best = -1, bestScore = 0;
  list.forEach((pr, i) => {
    const st = inp.stats?.[i];
    const g = Math.min(st?.games ?? 0, 3000), perf = Math.min(st?.perf[col] ?? 0, 3);
    let S = 0.005 * (perf * g + 5 * (3000 - g));
    const fl = pr.flags;
    if (mgr) {
      if (fl & 0x400) S += mgr.offside - 10;
      if (fl & 0x1000) S += 10 - mgr.attacking;
      if (fl & 0x100) S += mgr.pressing - 10;
      const fav = mgr.favourite;
      if (fav > 0 && fav < 10 && FAVOURITE_FORMATION[fav] && FAVOURITE_FORMATION[fav] === pr.formation) S *= n >= 11 ? Math.min(n * 0.2 - 0.2, 3.75) : 1.1;
      else S *= 0.1;
    }
    const cnt = [0, 0, 0, 0, 0];                                           // D (SW+D), DM, M, AM, F (float i originalen)
    let fit = 0;
    for (let s = 0; s < 11; s++) {
      const m = pr.masks[s], m2 = pr.masks2[s];
      if (mgr) {
        const lo = pr.lo[s] >>> 0;
        if (lo & 0x8000 && !(fl & 0x100)) S += mgr.pressing * 0.25 - 2.5;
        if (lo & 0x200000) S += mgr.freeRoles - 10;
        if (lo & 0x800000) S += mgr.attacking * 0.5 - 5;
        if (pr.tb[s] & 4) S += mgr.marking * 1.5 - 15;
      }
      let pos: number, side = -1;
      if (m & 1) { pos = 0; side = 2; } else if (m & 2) { cnt[0]++; pos = 1; } else if (m & 4) { cnt[0]++; pos = 2; } else if (m & 8) { cnt[1]++; pos = 3; }
      else if (m & 0x10) { cnt[2]++; pos = 4; } else if (m & 0x20) { cnt[3]++; pos = 5; } else { cnt[4]++; pos = 6; }
      for (let q = 0; q < SEC_MASK.length; q++) if (m2 & SEC_MASK[q][0]) { cnt[SEC_MASK[q][1]] += 0.5; pos = SEC_MASK[q][2]; break; }   // sekundær maske: ½ + dens position
      if (side < 0) side = m & 0x80 ? 0 : m & 0x100 ? 1 : m & 0x200 ? 2 : m & 0x400 ? 3 : 4;
      fit += T[pos * 5 + side];
    }
    const D = cnt[0], DM = cnt[1], AM = cnt[3], F = cnt[4], x = D - F;
    const W = 32 - (2 * F * F + AM * AM - 2 * D * D - DM * DM) - Math.abs(x - 0.5 * AM) * (x - AM);
    const Qs = 44 - 0.8 * W;
    if (mode === 1) S *= 1 + 0.015 * Qs; else if (mode === 3) S *= 1 - 0.015 * Qs; else if (mode === 4) S *= 1 - 0.025 * Qs;
    const sc = S * fit / div;
    scores.push(sc);
    if (best === -1 || sc > bestScore) { best = i; bestScore = sc; }
  });
  return { index: best, scores };
}
